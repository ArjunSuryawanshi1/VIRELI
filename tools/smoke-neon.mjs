import assert from "node:assert/strict";
import { randomUUID, randomBytes, createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import pg from "pg";

const metadata = JSON.parse(await readFile(process.argv[2], "utf8"));
const base = metadata.invocation_url;
const username = `__vireli_smoke_${randomUUID()}`;
const password = randomBytes(32).toString("base64url");
const device = randomBytes(32).toString("base64url");
const hash = (value) => createHash("sha256").update(value).digest("hex");
const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
async function call(path, { method = "GET", body, token } = {}) {
  const response = await fetch(new URL(path, base), {
    method, headers: { Origin: "https://arjunsuryawanshi1.github.io", "X-Vireli-Device": device, ...(body ? { "Content-Type": "application/json" } : {}), ...(token ? { Authorization: `Bearer ${token}` } : {}) },
    ...(body ? { body: JSON.stringify(body) } : {}), signal: AbortSignal.timeout(30000),
  });
  return { status: response.status, body: await response.json() };
}
try {
  const created = await call("/api/auth/vireli/register", { method: "POST", body: { username, password } });
  assert.equal(created.status, 200);
  assert.equal(created.body.authenticated, true);
  const token = created.body.sessionToken;
  const document = { profile: { name: "Deployment test" }, routine: { fixedActivities: [] } };
  const saved = await call("/api/planner", { method: "PUT", token, body: { revision: 0, document } });
  assert.equal(saved.status, 200);
  assert.equal(saved.body.revision, 1);
  const login = await call("/api/auth/vireli/login", { method: "POST", body: { username, password } });
  assert.equal(login.status, 200);
  assert.deepEqual((await call("/api/planner", { token: login.body.sessionToken })).body.document, document);
  assert.equal((await call("/api/planner", { method: "PUT", token, body: { revision: 0, document } })).status, 409);
  assert.equal((await call("/api/planner")).status, 401);
  await call("/api/auth/logout", { method: "POST", token });
  assert.equal((await call("/api/auth/me", { token })).body.authenticated, false);
  console.log("Hosted registration, login, planner persistence, revision conflict and logout passed.");
} finally {
  // The unique probe name and device are generated by this run; never delete real users.
  await pool.query("DELETE FROM vireli_users WHERE username=$1", [username]);
  await pool.query("DELETE FROM vireli_devices WHERE token_hash=$1", [hash(device)]);
  await pool.query("DELETE FROM vireli_rate_limits WHERE key=$1", [hash(`username:${username}`)]);
  await pool.end();
}
